// Writes words.js for the page: the voice's word timings (audio/vo.transcript.json,
// from eleven_scribe_v1) and how many words each script line has (the numbered
// rows of ../../scripts/rag-short.md), so each line becomes one cut.
// Usage: node make-words.js
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const words = JSON.parse(fs.readFileSync(path.join(dir, 'audio/vo.transcript.json'), 'utf8')).words
  .filter(w => w.type === 'word' && !w.text.startsWith('[')).map(w => ({ w: w.text, s: w.start, e: w.end }));
const md = fs.readFileSync(path.join(dir, '../../scripts/rag-short.md'), 'utf8');
const lines = [...md.matchAll(/^\| \d+ \| (.+?) \|/gm)].map(m => m[1].trim().split(/\s+/).length);
const total = lines.reduce((a, b) => a + b, 0);
if (total !== words.length) throw Error(`the script has ${total} words but the transcript has ${words.length}`);
fs.writeFileSync(path.join(dir, 'words.js'), `// Generated by make-words.js; do not edit by hand.
window.WORDS = ${JSON.stringify(words)};
window.LINE_WORDS = ${JSON.stringify(lines)};
`);
console.log(`words.js: ${words.length} words in ${lines.length} lines`);
