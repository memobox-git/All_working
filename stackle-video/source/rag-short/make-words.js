// Writes words.js for a Short's page: the voice's word timings (<dir>/audio/vo.transcript.json,
// from eleven_scribe_v1) and how many words each script line has (the numbered rows of the
// script's table), so each line becomes one cut.
// Usage: node make-words.js [short-dir] [script.md]   (defaults: this folder and ../../scripts/rag-short.md)
const fs = require('fs');
const path = require('path');
const dir = path.resolve(process.argv[2] || __dirname);
const script = path.resolve(process.argv[3] || path.join(__dirname, '../../scripts/rag-short.md'));
const words = JSON.parse(fs.readFileSync(path.join(dir, 'audio/vo.transcript.json'), 'utf8')).words
  .filter(w => w.type === 'word' && !w.text.startsWith('[')).map(w => ({ w: w.text, s: w.start, e: w.end }));
const lines = [...fs.readFileSync(script, 'utf8').matchAll(/^\| \d+ \| (.+?) \|/gm)].map(m => m[1].trim().split(/\s+/).length);
const total = lines.reduce((a, b) => a + b, 0);
if (total !== words.length) throw Error(`the script has ${total} words but the transcript has ${words.length}`);
fs.writeFileSync(path.join(dir, 'words.js'), `// Generated by make-words.js; do not edit by hand.
window.WORDS = ${JSON.stringify(words)};
window.LINE_WORDS = ${JSON.stringify(lines)};
`);
console.log(`words.js: ${words.length} words in ${lines.length} lines`);
