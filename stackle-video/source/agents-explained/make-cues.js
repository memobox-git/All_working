// Writes cues.js from a word-timed transcript of the voiceover, so the
// graphics land on the spoken words.
// Usage: node make-cues.js <transcript.json> [offset-seconds]
const fs = require('fs');
const path = require('path');

const [src, offArg] = process.argv.slice(2);
const tr = JSON.parse(fs.readFileSync(src, 'utf8'));
const words = tr.words.filter(w => w.type === 'word').map(w => ({ w: w.text, s: w.start, e: w.end }));
const duration = words[words.length - 1].e;
const out = `// Voiceover word timings. Generated by make-cues.js; do not edit by hand.
window.VO = ${JSON.stringify({ offset: Number(offArg || 0.8), duration, words })};
`;
fs.writeFileSync(path.join(__dirname, 'cues.js'), out);
console.log('wrote cues.js:', words.length, 'words,', duration, 's');
