// Writes a cues file from an ElevenLabs transcript of the voiceover, so the
// graphics land on the spoken words.
// Usage: node make-cues.js <transcript.json> <offset-seconds> <out.js>
const fs = require('fs');

const [src, offArg, outFile] = process.argv.slice(2);
const tr = JSON.parse(fs.readFileSync(src, 'utf8'));
const words = tr.words.filter(w => w.type === 'word').map(w => ({ w: w.text, s: w.start, e: w.end }));
const duration = words[words.length - 1].e;
const out = `// Voiceover word timings (ElevenLabs alignment). Generated by make-cues.js; do not edit by hand.
window.VO = ${JSON.stringify({ offset: Number(offArg || 0.8), duration, words })};
`;
fs.writeFileSync(outFile, out);
console.log('wrote', outFile + ':', words.length, 'words,', duration, 's');
