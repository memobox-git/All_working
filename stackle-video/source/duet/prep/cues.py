"""Writes work/cues.js for the scene: the word timings, the section times and how many
frames each clip has. Usage: python3 cues.py <work-dir>"""
import json, os, sys
work = sys.argv[1]
words = json.load(open(os.path.join(work, 'words.json')))
sections = json.load(open(os.path.join(work, 'sections.json')))
clips = {d: len([f for f in os.listdir(os.path.join(work, 'clips', d)) if f.endswith('.jpg')])
         for d in sorted(os.listdir(os.path.join(work, 'clips')))}
with open(os.path.join(work, 'cues.js'), 'w') as f:
    f.write('// Generated by prep/cues.py from the voice-over; do not edit by hand.\n')
    f.write(f'window.WORDS = {json.dumps(words)};\n')
    f.write(f'window.SECTIONS = {json.dumps(sections)};\n')
    f.write(f'window.CLIPFRAMES = {json.dumps(clips)};\n')
print(len(words), 'words;', clips)
