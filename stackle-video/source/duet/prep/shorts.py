"""Cuts the vertical Shorts out of the long video's voice track. Each Short is a list of
spans of the 8-minute voice-over; this joins them with short beats, keeps the word timings
(moved to the Short's own clock and spelled for captions), and writes what the scene needs.
Usage: python3 shorts.py <work-dir>     -> work/shorts/<id>/{voice.wav, sections.json, cues.js}"""
import json, os, re, subprocess, sys
import numpy as np

SR = 48000
LEAD, GAP, TAIL = 0.35, 0.3, 2.6       # before the first word, between spans, end card after the last word

# spans are seconds on the long video's clock, from audio/words.json (start of first word, end of last)
SHORTS = {
    'in45':   {'title': 'Claude Duet in under a minute',          'spans': [(1.2, 17.58), (65.02, 95.0)]},
    'vs':     {'title': 'Claude Duet vs Grok Bot vs Muse vs Dots', 'spans': [(376.31, 443.67)]},
    'safety': {'title': 'How Claude Duet keeps you safe',         'spans': [(178.0, 189.18), (189.76, 209.26), (209.82, 229.22)]},
    'catch':  {'title': 'The catch with Claude Duet',             'spans': [(255.51, 280.96), (281.12, 308.14)]},
    'parts':  {'title': 'The 6 parts of every AI agent',          'spans': [(100.19, 156.37), (157.28, 174.78), (175.42, 189.18)]},
}
# how Whisper wrote a word -> how the captions should show it
SPELL = {'GrokBot': 'Grok Bot', 'XAI': 'xAI', 'testers': "tester's", 'webpage': 'web page', '4000': '4,000',
         'plans': "plan's", 'Wallet,': 'wallet,'}

work = sys.argv[1]
pcm = subprocess.run(['ffmpeg', '-loglevel', 'error', '-i', os.path.join(work, 'voice.wav'), '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'],
                     capture_output=True, check=True).stdout
voice = np.frombuffer(pcm, np.float32)
words = json.load(open(os.path.join(work, 'words.json')))
clips = json.load(open(os.path.join(work, 'clipframes.json'))) if os.path.exists(os.path.join(work, 'clipframes.json')) else \
    {d: len([f for f in os.listdir(os.path.join(work, 'clips', d)) if f.endswith('.jpg')]) for d in os.listdir(os.path.join(work, 'clips'))}


def tidy(ws):
    """Glues Whisper's split tokens back together (',000', '-time', '.5') and fixes spellings."""
    out = []
    for w in ws:
        t = w['w']
        if out and re.match(r'^[,.\-]\w', t):
            out[-1]['w'] += t; out[-1]['e'] = w['e']; continue
        out.append(dict(w, w=SPELL.get(t, t)))
    # "Dev Day," -> "DevDay,"
    res = []
    for w in out:
        if res and res[-1]['w'] == 'Dev' and w['w'].startswith('Day'):
            res[-1]['w'] = 'Dev' + w['w']; res[-1]['e'] = w['e']; continue
        if res and res[-1]['w'] == 'wait' and w['w'].startswith('list'):
            res[-1]['w'] = 'wait' + w['w']; res[-1]['e'] = w['e']; continue
        if w['w'] in ('co-work', 'co'):
            w['w'] = 'Cowork'
        res.append(w)
    res = [w for w in res if w['w'] not in ('-work',)]
    # a span can start mid-sentence in the long video ("the sixth part"); capitalise after a full stop
    for a, b in zip(res, res[1:]):
        if re.search(r'[.?!]$', a['w']) and b['w'][:1].islower() and b['w'] != 'xAI':
            b['w'] = b['w'][0].upper() + b['w'][1:]
    return res


for sid, sh in SHORTS.items():
    d = os.path.join(work, 'shorts', sid); os.makedirs(d, exist_ok=True)
    parts, short_words, sections, t = [], [], [], LEAD
    for k, (a, b) in enumerate(sh['spans']):
        pa, pb = int((a - 0.08) * SR), int((b + 0.12) * SR)
        x = voice[pa:pb].copy(); f = int(0.012 * SR)
        x[:f] *= np.linspace(0, 1, f); x[-f:] *= np.linspace(1, 0, f)
        start = t; parts.append((start, x))
        for w in words:
            if a - 0.01 <= w['s'] and w['e'] <= b + 0.05:
                short_words.append({'w': w['w'], 's': round(start + 0.08 + w['s'] - a, 3), 'e': round(start + 0.08 + w['e'] - a, 3), 'src': w['s'], 'sec': k + 1})
        sections.append({'n': k + 1, 'start': round(start + 0.08, 3), 'end': round(start + 0.08 + b - a, 3), 'src': [a, b]})
        t += len(x) / SR + GAP
    dur = round(t - GAP + TAIL, 3)
    track = np.zeros(int(dur * SR), np.float32)
    for start, x in parts:
        i = int(start * SR); track[i:i + len(x)] = x[:len(track) - i]
    raw = (np.clip(track, -1, 1) * 32767).astype('<i2').tobytes()
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-f', 's16le', '-ar', str(SR), '-ac', '1', '-i', '-', os.path.join(d, 'voice.wav')], input=raw, check=True)
    short_words = tidy(short_words)
    json.dump({'duration': dur, 'flat': True, 'sections': sections}, open(os.path.join(d, 'sections.json'), 'w'), indent=1)
    with open(os.path.join(d, 'cues.js'), 'w') as f:
        f.write('// Generated by prep/shorts.py; do not edit by hand.\n')
        f.write(f'window.SHORT = {json.dumps(sid)}; window.TITLE = {json.dumps(sh["title"])};\n')
        f.write(f'window.WORDS = {json.dumps(short_words)};\n')
        f.write(f'window.SECTIONS = {json.dumps({"duration": dur, "sections": sections})};\n')
        f.write(f'window.CLIPFRAMES = {json.dumps(clips)};\n')
    print(f'{sid}: {dur:.1f}s, {len(short_words)} words')
